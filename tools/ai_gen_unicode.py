#!/usr/bin/env python3
"""Generate the Unicode category range tables embedded in src/gguf.cpp.

The Qwen2 pre-tokenizer regex needs \\p{L} / \\p{N} / \\s semantics; we embed
compact sorted range tables instead of pulling in a Unicode library.

Usage:
  python ai_gen_unicode.py <path-to-gguf.cpp>

Rewrites the block between the markers:
  // === BEGIN GENERATED UNICODE TABLES ===
  // === END GENERATED UNICODE TABLES ===
"""
import sys
import unicodedata


def ranges_for(pred):
    out = []
    start = None
    prev = None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok:
            if start is None:
                start = cp
            prev = cp
        else:
            if start is not None:
                out.append((start, prev))
                start = None
    if start is not None:
        out.append((start, prev))
    return out


def is_letter(cp):
    return unicodedata.category(chr(cp)).startswith("L")


def is_number(cp):
    return unicodedata.category(chr(cp)).startswith("N")


# ECMAScript / Oniguruma \s (llama.cpp's unicode regex) whitespace set.
WS = [0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680] + list(range(0x2000, 0x200B)) + [
    0x2028, 0x2029, 0x202F, 0x205F, 0x3000
]


def emit_ranges(name, rs):
    lines = ["static const uint32_t %s[][2] = {" % name]
    row = []
    for a, b in rs:
        row.append("{0x%X,0x%X}" % (a, b))
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    lines.append("static const int %s_n = (int)(sizeof(%s) / sizeof(%s[0]));" % (name, name, name))
    return "\n".join(lines)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    path = sys.argv[1]
    letter = ranges_for(is_letter)
    number = ranges_for(is_number)
    block = []
    block.append("// --- generated by tools/ai_gen_unicode.py (python unicodedata %s, unicode %s) ---"
                 % (sys.version.split()[0], unicodedata.unidata_version))
    block.append(emit_ranges("kLetterRanges", letter))
    block.append(emit_ranges("kNumberRanges", number))
    ws = sorted(set(WS))
    block.append("static const uint32_t kSpaceCp[] = {%s};" %
                 ", ".join("0x%X" % c for c in ws))
    block.append("static const int kSpaceCp_n = (int)(sizeof(kSpaceCp) / sizeof(kSpaceCp[0]));")
    new = "\n".join(block)
    src = open(path, "r", encoding="utf-8").read()
    begin = "// === BEGIN GENERATED UNICODE TABLES ==="
    end = "// === END GENERATED UNICODE TABLES ==="
    i = src.index(begin)
    j = src.index(end)
    out = src[: i + len(begin)] + "\n" + new + "\n" + src[j:]
    open(path, "w", encoding="utf-8", newline="\n").write(out)
    print("patched %s: %d letter ranges, %d number ranges, %d whitespace cps"
          % (path, len(letter), len(number), len(ws)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
