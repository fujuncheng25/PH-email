struct Tokenizer::Impl {
  std::vector<std::string> tokens;
  std::vector<int32_t> types;
  std::unordered_map<std::string, int32_t> tok_id;
  std::unordered_map<std::string, int32_t> merge_rank;
  std::vector<std::pair<std::string, int32_t>> specials;  // 按文本长度降序
  std::string byte_str[256];
  std::vector<std::pair<uint32_t, uint8_t>> cp2byte;  // 按码点排序
  int32_t bos = 151643, eos = 151645, pad = 151643;
  bool ready = false;

  void build_byte_maps();
  void encode_plain(const std::string& text, std::vector<int>& ids) const;
};

void Tokenizer::Impl::build_byte_maps() {
  bool present[256] = {false};
  std::vector<int> bs, cs;
  auto add = [&](int lo, int hi) {
    for (int b = lo; b <= hi; ++b) {
      bs.push_back(b);
      cs.push_back(b);
      present[b] = true;
    }
  };
  add(0x21, 0x7E);
  add(0xA1, 0xAC);
  add(0xAE, 0xFF);
  int n = 0;
  for (int b = 0; b < 256; ++b) {
    if (!present[b]) {
      bs.push_back(b);
      cs.push_back(256 + n);
      ++n;
    }
  }
  cp2byte.clear();
  for (size_t k = 0; k < bs.size(); ++k) {
    byte_str[bs[k]].clear();
    utf8_append(byte_str[bs[k]], (uint32_t)cs[k]);
    cp2byte.push_back({(uint32_t)cs[k], (uint8_t)bs[k]});
  }
  std::sort(cp2byte.begin(), cp2byte.end(),
            [](const std::pair<uint32_t, uint8_t>& a, const std::pair<uint32_t, uint8_t>& b) {
              return a.first < b.first;
            });
}

// 在位置 i 匹配 Qwen2 预切分正则的某一个分支，返回消耗字节数（0=不匹配）。
// regex: (?i:'s|'t|'re|'ve|'m|'ll|'d)|[^\r\n\p{L}\p{N}]?\p{L}+|\p{N}|
//        ?[^\s\p{L}\p{N}]+[\r\n]*|\s*[\r\n]+|\s+(?!\S)|\s+
static size_t match_qwen2_pretok(const std::string& t, size_t i) {
  size_t len = 0;
  const uint32_t cp = utf8_decode(t, i, len);
  auto lc = [&](size_t k) -> int {
    if (k >= t.size()) return -1;
    return std::tolower((unsigned char)t[k]);
  };
  // 1) 英文缩写
  if (cp == '\'') {
    const int c1 = lc(i + 1);
    if (c1 == 's' || c1 == 't' || c1 == 'm' || c1 == 'd') return 2;
    const int c2 = lc(i + 2);
    if ((c1 == 'r' && c2 == 'e') || (c1 == 'v' && c2 == 'e') || (c1 == 'l' && c2 == 'l')) return 3;
  }
  // 2) [^\r\n\p{L}\p{N}]?\p{L}+
  if (cp_is_letter(cp)) {
    size_t j = i;
    for (;;) {
      size_t l;
      const uint32_t c = utf8_decode(t, j, l);
      if (!cp_is_letter(c)) break;
      j += l;
    }
    return j - i;
  }
  if (cp != '\r' && cp != '\n' && !cp_is_number(cp)) {
    size_t j = i + len;
    if (j < t.size()) {
      size_t l2;
      const uint32_t c2 = utf8_decode(t, j, l2);
      if (cp_is_letter(c2)) {
        j += l2;
        for (;;) {
          size_t l;
          const uint32_t c = utf8_decode(t, j, l);
          if (!cp_is_letter(c)) break;
          j += l;
        }
        return j - i;
      }
    }
  }
  // 3) \p{N}
  if (cp_is_number(cp)) return len;
  // 4)  ?[^\s\p{L}\p{N}]+[\r\n]*
  {
    size_t j = i;
    if (cp == ' ') j += 1;
    size_t k = j;
    for (;;) {
      if (k >= t.size()) break;
      size_t l;
      const uint32_t c = utf8_decode(t, k, l);
      if (cp_is_space(c) || cp_is_letter(c) || cp_is_number(c)) break;
      k += l;
    }
    if (k > j) {
      while (k < t.size() && (t[k] == '\r' || t[k] == '\n')) ++k;
      return k - i;
    }
  }
  // 5) \s*[\r\n]+
  if (cp_is_space(cp)) {
    size_t k = i;
    for (;;) {
      if (k >= t.size()) break;
      size_t l;
      const uint32_t c = utf8_decode(t, k, l);
      if (!cp_is_space(c)) break;
      k += l;
    }
    // 找最大的 q < k 使 t[q] 起始为 \r/\n，然后 [\r\n]+ 贪心
    for (size_t q = k; q > i;) {
      --q;
      if (t[q] == '\r' || t[q] == '\n') {
        size_t e = q;
        while (e < k && (t[e] == '\r' || t[e] == '\n')) ++e;
        return e - i;
      }
    }
  }
  // 6) \s+(?!\S)
  if (cp_is_space(cp)) {
    size_t k = i;
    size_t last_start = i;
    int count = 0;
    for (;;) {
      if (k >= t.size()) break;
      size_t l;
      const uint32_t c = utf8_decode(t, k, l);
      if (!cp_is_space(c)) break;
      last_start = k;
      ++count;
      k += l;
    }
    if (k >= t.size()) return k - i;  // 整段到结尾
    if (count >= 2) return last_start - i;  // 留最后一个空白给后续分支
  }
  // 7) \s+
  if (cp_is_space(cp)) {
    size_t k = i;
    for (;;) {
      if (k >= t.size()) break;
      size_t l;
      const uint32_t c = utf8_decode(t, k, l);
      if (!cp_is_space(c)) break;
      k += l;
    }
    return k - i;
  }
  return 0;
}

static std::vector<std::pair<size_t, size_t>> pretokenize(const std::string& t) {
  std::vector<std::pair<size_t, size_t>> out;
  size_t i = 0;
  while (i < t.size()) {
    size_t len = match_qwen2_pretok(t, i);
    if (len == 0) {
      size_t l;
      utf8_decode(t, i, l);
      len = l;
    }
    out.push_back({i, len});
    i += len;
  }
  return out;
}

void Tokenizer::Impl::encode_plain(const std::string& text, std::vector<int>& ids) const {
  const auto chunks = pretokenize(text);
  for (const auto& ch : chunks) {
    std::vector<std::string> syms;
    syms.reserve(ch.second);
    for (size_t k = 0; k < ch.second; ++k) {
      syms.push_back(byte_str[(unsigned char)text[ch.first + k]]);
    }
    while (syms.size() > 1) {
      int best_rank = std::numeric_limits<int>::max();
      size_t best = 0;
      bool found = false;
      for (size_t k = 0; k + 1 < syms.size(); ++k) {
        std::string key;
        key.reserve(syms[k].size() + syms[k + 1].size() + 1);
        key += syms[k];
        key.push_back('\x01');
        key += syms[k + 1];
        auto it = merge_rank.find(key);
        if (it != merge_rank.end() && it->second < best_rank) {
          best_rank = it->second;
          best = k;
          found = true;
        }
      }
      if (!found) break;
      syms[best] += syms[best + 1];
      syms.erase(syms.begin() + (long)best + 1);
    }
    for (const std::string& s : syms) {
      auto it = tok_id.find(s);
      if (it != tok_id.end()) {
        ids.push_back(it->second);
        continue;
      }
      // 回退：按字节拆
      for (size_t k = 0; k < s.size();) {
        size_t l;
        const uint32_t cp = utf8_decode(s, k, l);
        int byte = -1;
        auto it2 = std::lower_bound(
            cp2byte.begin(), cp2byte.end(), cp,
            [](const std::pair<uint32_t, uint8_t>& a, uint32_t v) { return a.first < v; });
        if (it2 != cp2byte.end() && it2->first == cp) byte = it2->second;
        if (byte >= 0) {
          auto it3 = tok_id.find(byte_str[byte]);
          if (it3 != tok_id.end()) ids.push_back(it3->second);
        }
        k += l;
      }
    }
  }
}

