bool Tokenizer::init(const Model& model, std::string& err) {
  impl_.reset(new Impl());
  Impl& im = *impl_;
  im.build_byte_maps();
  const auto* tokens = model.get_str_array("tokenizer.ggml.tokens");
  if (!tokens || tokens->empty()) {
    err = "模型缺少 tokenizer.ggml.tokens";
    return false;
  }
  im.tokens = *tokens;
  const auto* types = model.get_int_array("tokenizer.ggml.token_type");
  im.types.assign(im.tokens.size(), 1);
  if (types && types->size() == im.tokens.size()) {
    for (size_t i = 0; i < im.tokens.size(); ++i) im.types[i] = (int32_t)(*types)[i];
  }
  const auto* merges = model.get_str_array("tokenizer.ggml.merges");
  if (!merges) {
    err = "模型缺少 tokenizer.ggml.merges";
    return false;
  }
  im.tok_id.reserve(im.tokens.size() * 2);
  for (size_t i = 0; i < im.tokens.size(); ++i) {
    im.tok_id.emplace(im.tokens[i], (int32_t)i);
  }
  im.merge_rank.reserve(merges->size() * 2);
  for (size_t i = 0; i < merges->size(); ++i) {
    const std::string& m = (*merges)[i];
    const size_t sp = m.find(' ');
    if (sp == std::string::npos || sp == 0 || sp + 1 >= m.size()) continue;
    std::string key;
    key.reserve(m.size());
    key.append(m, 0, sp);
    key.push_back('\x01');
    key.append(m, sp + 1, std::string::npos);
    im.merge_rank.emplace(std::move(key), (int32_t)i);
  }
  im.bos = (int32_t)model.get_int("tokenizer.ggml.bos_token_id", 151643);
  im.eos = (int32_t)model.get_int("tokenizer.ggml.eos_token_id", 151645);
  im.pad = (int32_t)model.get_int("tokenizer.ggml.padding_token_id", im.bos);
  // 特殊 token：control(3) / user_defined(4)
  for (size_t i = 0; i < im.tokens.size(); ++i) {
    const int32_t ty = im.types[i];
    if ((ty == 3 || ty == 4) && !im.tokens[i].empty()) {
      im.specials.push_back({im.tokens[i], (int32_t)i});
    }
  }
  std::sort(im.specials.begin(), im.specials.end(),
            [](const std::pair<std::string, int32_t>& a, const std::pair<std::string, int32_t>& b) {
              if (a.first.size() != b.first.size()) return a.first.size() > b.first.size();
              return a.second < b.second;
            });
  im.ready = true;
  return true;
}

std::vector<int> Tokenizer::encode(const std::string& text, bool parse_special) const {
  std::vector<int> ids;
  if (!impl_ || !impl_->ready || text.empty()) return ids;
  if (!parse_special || impl_->specials.empty()) {
    impl_->encode_plain(text, ids);
    return ids;
  }
  size_t i = 0;
  size_t plain_start = 0;
  while (i < text.size()) {
    const std::pair<std::string, int32_t>* hit = nullptr;
    for (const auto& sp : impl_->specials) {
      if (text.compare(i, sp.first.size(), sp.first) == 0) {
        hit = &sp;
        break;
      }
    }
    if (hit) {
      if (i > plain_start) {
        impl_->encode_plain(text.substr(plain_start, i - plain_start), ids);
      }
      ids.push_back(hit->second);
      i += hit->first.size();
      plain_start = i;
    } else {
      size_t l;
      utf8_decode(text, i, l);
      i += l;
    }
  }
  if (plain_start < text.size()) {
    impl_->encode_plain(text.substr(plain_start), ids);
  }
  return ids;
}

std::string Tokenizer::decode(const std::vector<int>& ids, bool keep_special) const {
  std::string out;
  if (!impl_ || impl_->tokens.empty()) return out;
  for (int id : ids) {
    if (id < 0 || id >= (int)impl_->tokens.size()) continue;
    const int32_t ty = id < (int)impl_->types.size() ? impl_->types[id] : 1;
    if (!keep_special && (ty == 3 || ty == 4)) continue;  // 跳过特殊 token
    if (ty == 5) continue;                               // 跳过未使用 token
    const std::string& s = impl_->tokens[(size_t)id];
    for (size_t k = 0; k < s.size();) {
      size_t l;
      const uint32_t cp = utf8_decode(s, k, l);
      int byte = -1;
      auto it = std::lower_bound(
          impl_->cp2byte.begin(), impl_->cp2byte.end(), cp,
          [](const std::pair<uint32_t, uint8_t>& a, uint32_t v) { return a.first < v; });
      if (it != impl_->cp2byte.end() && it->first == cp) byte = it->second;
      if (byte >= 0) {
        out.push_back((char)byte);
      } else {
        utf8_append(out, cp);
      }
      k += l;
    }
  }
  return out;
}

