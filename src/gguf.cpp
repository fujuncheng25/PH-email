// ---- Q4_K / Q5_K 共用的 6 位 scale/min 解包 ----
static inline void get_scale_min_k4(int j, const uint8_t* q, uint8_t& d, uint8_t& m) {
  if (j < 4) {
    d = (uint8_t)(q[j] & 63);
    m = (uint8_t)(q[j + 4] & 63);
  } else {
    d = (uint8_t)((q[j + 4] & 0x0F) | ((q[j - 4] >> 6) << 4));
    m = (uint8_t)((q[j + 4] >> 4) | ((q[j] >> 6) << 4));
  }
}

static float dot_row_impl(uint32_t type, const uint8_t* row, int n, const float* x) {
  switch (type) {
    case T_F32: {
      const float* p = (const float*)row;
      float a = 0.f;
      for (int i = 0; i < n; ++i) a += p[i] * x[i];
      return a;
    }
    case T_F16: {
      const uint16_t* p = (const uint16_t*)row;
      float a = 0.f;
      for (int i = 0; i < n; ++i) a += fp16_to_f32(p[i]) * x[i];
      return a;
    }
    case T_BF16: {
      const uint16_t* p = (const uint16_t*)row;
      float a = 0.f;
      for (int i = 0; i < n; ++i) a += bf16_to_f32(p[i]) * x[i];
      return a;
    }
    case T_Q8_0: {
      float a = 0.f;
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 34;
        const float d = fp16_to_f32(rd_u16(blk));
        const int8_t* q = (const int8_t*)(blk + 2);
        const float* xb = x + (size_t)b * 32;
        float s = 0.f;
        for (int j = 0; j < 32; ++j) s += (float)q[j] * xb[j];
        a += d * s;
      }
      return a;
    }
    case T_Q4_0: {
      float a = 0.f;
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 18;
        const float d = fp16_to_f32(rd_u16(blk));
        const uint8_t* q = blk + 2;
        const float* xb = x + (size_t)b * 32;
        float s = 0.f;
        for (int j = 0; j < 16; ++j) {
          s += (float)((int)(q[j] & 0x0F) - 8) * xb[j];
          s += (float)((int)(q[j] >> 4) - 8) * xb[j + 16];
        }
        a += d * s;
      }
      return a;
    }
    case T_Q4_1: {
      float a = 0.f;
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 20;
        const float d = fp16_to_f32(rd_u16(blk));
        const float m = fp16_to_f32(rd_u16(blk + 2));
        const uint8_t* q = blk + 4;
        const float* xb = x + (size_t)b * 32;
        float sx = 0.f, sq = 0.f;
        for (int j = 0; j < 16; ++j) {
          sx += xb[j] + xb[j + 16];
          sq += (float)(q[j] & 0x0F) * xb[j] + (float)(q[j] >> 4) * xb[j + 16];
        }
        a += d * sq + m * sx;
      }
      return a;
    }
    case T_Q5_0: {
      float a = 0.f;
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 22;
        const float d = fp16_to_f32(rd_u16(blk));
        const uint8_t* qh = blk + 2;
        const uint8_t* q = blk + 6;
        const uint32_t qh32 = rd_u32(qh);
        const float* xb = x + (size_t)b * 32;
        float s = 0.f;
        for (int j = 0; j < 16; ++j) {
          const int xh0 = (int)(((qh32 >> (j + 0)) << 4) & 0x10);
          const int xh1 = (int)((qh32 >> (j + 12)) & 0x10);
          const int q0 = ((q[j] & 0x0F) | xh0) - 16;
          const int q1 = ((q[j] >> 4) | xh1) - 16;
          s += (float)q0 * xb[j] + (float)q1 * xb[j + 16];
        }
        a += d * s;
      }
      return a;
    }
    case T_Q5_1: {
      float a = 0.f;
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 24;
        const float d = fp16_to_f32(rd_u16(blk));
        const float m = fp16_to_f32(rd_u16(blk + 2));
        const uint8_t* qh = blk + 4;
        const uint8_t* q = blk + 8;
        const uint32_t qh32 = rd_u32(qh);
        const float* xb = x + (size_t)b * 32;
        float sx = 0.f, sq = 0.f;
        for (int j = 0; j < 16; ++j) {
          const int xh0 = (int)(((qh32 >> (j + 0)) << 4) & 0x10);
          const int xh1 = (int)((qh32 >> (j + 12)) & 0x10);
          const int q0 = ((q[j] & 0x0F) | xh0);
          const int q1 = ((q[j] >> 4) | xh1);
          sq += (float)q0 * xb[j] + (float)q1 * xb[j + 16];
          sx += xb[j] + xb[j + 16];
        }
        a += d * sq + m * sx;
      }
      return a;
    }
    case T_Q4_K: {
      float a = 0.f;
      for (int b = 0; b < n / 256; ++b) {
        const uint8_t* blk = row + (size_t)b * 144;
        const float d = fp16_to_f32(rd_u16(blk));
        const float dmin = fp16_to_f32(rd_u16(blk + 2));
        const uint8_t* scales = blk + 4;
        const uint8_t* qs = blk + 16;
        const float* xb = x + (size_t)b * 256;
        int is = 0;
        for (int j = 0; j < 256; j += 64) {
          uint8_t sc, mn;
          get_scale_min_k4(is + 0, scales, sc, mn);
          const float d1 = d * (float)sc, m1 = dmin * (float)mn;
          get_scale_min_k4(is + 1, scales, sc, mn);
          const float d2 = d * (float)sc, m2 = dmin * (float)mn;
          const float* x0 = xb + j;
          const float* x1 = xb + j + 32;
          float s1 = 0.f, s2 = 0.f;
          for (int l = 0; l < 32; ++l) {
            s1 += ((float)(qs[l] & 0x0F) * d1 - m1) * x0[l];
            s2 += ((float)(qs[l] >> 4) * d2 - m2) * x1[l];
          }
          a += s1 + s2;
          qs += 32;
          is += 2;
        }
      }
      return a;
    }
    case T_Q5_K: {
      float a = 0.f;
      for (int b = 0; b < n / 256; ++b) {
        const uint8_t* blk = row + (size_t)b * 176;
        const float d = fp16_to_f32(rd_u16(blk));
        const float dmin = fp16_to_f32(rd_u16(blk + 2));
        const uint8_t* scales = blk + 4;
        const uint8_t* qh = blk + 16;  // 32 字节：256 个高位的 bit 数组，bit 下标 = 块内元素下标
        const uint8_t* qs = blk + 48;
        const float* xb = x + (size_t)b * 256;
        int is = 0;
        for (int j = 0; j < 256; j += 64) {
          uint8_t sc, mn;
          get_scale_min_k4(is + 0, scales, sc, mn);
          const float d1 = d * (float)sc, m1 = dmin * (float)mn;
          get_scale_min_k4(is + 1, scales, sc, mn);
          const float d2 = d * (float)sc, m2 = dmin * (float)mn;
          // qh 为 32 字节：qh[l] 的 bit(2g) 是 q1 的第 5 位，bit(2g+1) 是 q2 的第 5 位
          const unsigned mask1 = 1u << (2 * (j / 64));
          const unsigned mask2 = 1u << (2 * (j / 64) + 1);
          const float* x0 = xb + j;
          const float* x1 = xb + j + 32;
          float s1 = 0.f, s2 = 0.f;
          for (int l = 0; l < 32; ++l) {
            const int h1 = (qh[l] & mask1) ? 16 : 0;
            const int h2 = (qh[l] & mask2) ? 16 : 0;
            s1 += ((float)((qs[l] & 0x0F) + h1) * d1 - m1) * x0[l];
            s2 += ((float)((qs[l] >> 4) + h2) * d2 - m2) * x1[l];
          }
          a += s1 + s2;
          qs += 32;
          is += 2;
        }
      }
      return a;
    }
    case T_Q6_K: {
      float a = 0.f;
      for (int b = 0; b < n / 256; ++b) {
        const uint8_t* blk = row + (size_t)b * 210;
        const float d = fp16_to_f32(rd_u16(blk + 208));
        const uint8_t* ql = blk;
        const uint8_t* qh = blk + 128;
        const int8_t* sc = (const int8_t*)(blk + 192);
        const float* xb = x + (size_t)b * 256;
        for (int nb = 0; nb < 2; ++nb) {
          const float* y0 = xb + nb * 128;
          for (int l = 0; l < 32; ++l) {
            const int is = l / 16;
            const int q1 = (int)((int8_t)((ql[l + 0] & 0x0F) | (((qh[l] >> 0) & 3) << 4))) - 32;
            const int q2 = (int)((int8_t)((ql[l + 32] & 0x0F) | (((qh[l] >> 2) & 3) << 4))) - 32;
            const int q3 = (int)((int8_t)((ql[l + 0] >> 4) | (((qh[l] >> 4) & 3) << 4))) - 32;
            const int q4 = (int)((int8_t)((ql[l + 32] >> 4) | (((qh[l] >> 6) & 3) << 4))) - 32;
            a += d * (float)sc[is + 0] * (float)q1 * y0[l + 0];
            a += d * (float)sc[is + 2] * (float)q2 * y0[l + 32];
            a += d * (float)sc[is + 4] * (float)q3 * y0[l + 64];
            a += d * (float)sc[is + 6] * (float)q4 * y0[l + 96];
          }
          ql += 64;
          qh += 32;
          sc += 8;
        }
      }
      return a;
    }
    default:
      return 0.f;
  }
}

static void dequant_row_impl(uint32_t type, const uint8_t* row, int n, float* out) {
  switch (type) {
    case T_F32:
      std::memcpy(out, row, (size_t)n * 4);
      return;
    case T_F16: {
      const uint16_t* p = (const uint16_t*)row;
      for (int i = 0; i < n; ++i) out[i] = fp16_to_f32(p[i]);
      return;
    }
    case T_BF16: {
      const uint16_t* p = (const uint16_t*)row;
      for (int i = 0; i < n; ++i) out[i] = bf16_to_f32(p[i]);
      return;
    }
    case T_Q8_0: {
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 34;
        const float d = fp16_to_f32(rd_u16(blk));
        const int8_t* q = (const int8_t*)(blk + 2);
        for (int j = 0; j < 32; ++j) out[b * 32 + j] = d * (float)q[j];
      }
      return;
    }
    case T_Q4_0: {
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 18;
        const float d = fp16_to_f32(rd_u16(blk));
        const uint8_t* q = blk + 2;
        for (int j = 0; j < 16; ++j) {
          out[b * 32 + j] = d * (float)((int)(q[j] & 0x0F) - 8);
          out[b * 32 + j + 16] = d * (float)((int)(q[j] >> 4) - 8);
        }
      }
      return;
    }
    case T_Q4_1: {
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 20;
        const float d = fp16_to_f32(rd_u16(blk));
        const float m = fp16_to_f32(rd_u16(blk + 2));
        const uint8_t* q = blk + 4;
        for (int j = 0; j < 16; ++j) {
          out[b * 32 + j] = d * (float)(q[j] & 0x0F) + m;
          out[b * 32 + j + 16] = d * (float)(q[j] >> 4) + m;
        }
      }
      return;
    }
    case T_Q5_0: {
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 22;
        const float d = fp16_to_f32(rd_u16(blk));
        const uint32_t qh = rd_u32(blk + 2);
        const uint8_t* q = blk + 6;
        for (int j = 0; j < 16; ++j) {
          const int xh0 = (int)(((qh >> (j + 0)) << 4) & 0x10);
          const int xh1 = (int)((qh >> (j + 12)) & 0x10);
          out[b * 32 + j] = d * (float)(((q[j] & 0x0F) | xh0) - 16);
          out[b * 32 + j + 16] = d * (float)(((q[j] >> 4) | xh1) - 16);
        }
      }
      return;
    }
    case T_Q5_1: {
      for (int b = 0; b < n / 32; ++b) {
        const uint8_t* blk = row + (size_t)b * 24;
        const float d = fp16_to_f32(rd_u16(blk));
        const float m = fp16_to_f32(rd_u16(blk + 2));
        const uint32_t qh = rd_u32(blk + 4);
        const uint8_t* q = blk + 8;
        for (int j = 0; j < 16; ++j) {
          const int xh0 = (int)(((qh >> (j + 0)) << 4) & 0x10);
          const int xh1 = (int)((qh >> (j + 12)) & 0x10);
          out[b * 32 + j] = d * (float)((q[j] & 0x0F) | xh0) + m;
          out[b * 32 + j + 16] = d * (float)((q[j] >> 4) | xh1) + m;
        }
      }
      return;
    }
    case T_Q4_K: {
      for (int b = 0; b < n / 256; ++b) {
        const uint8_t* blk = row + (size_t)b * 144;
        const float d = fp16_to_f32(rd_u16(blk));
        const float dmin = fp16_to_f32(rd_u16(blk + 2));
        const uint8_t* scales = blk + 4;
        const uint8_t* qs = blk + 16;
        float* y = out + (size_t)b * 256;
        int is = 0;
        for (int j = 0; j < 256; j += 64) {
          uint8_t sc, mn;
          get_scale_min_k4(is + 0, scales, sc, mn);
          const float d1 = d * (float)sc, m1 = dmin * (float)mn;
          get_scale_min_k4(is + 1, scales, sc, mn);
          const float d2 = d * (float)sc, m2 = dmin * (float)mn;
          for (int l = 0; l < 32; ++l) y[j + l] = d1 * (float)(qs[l] & 0x0F) - m1;
          for (int l = 0; l < 32; ++l) y[j + 32 + l] = d2 * (float)(qs[l] >> 4) - m2;
          qs += 32;
          is += 2;
        }
      }
      return;
    }
    case T_Q5_K: {
      for (int b = 0; b < n / 256; ++b) {
        const uint8_t* blk = row + (size_t)b * 176;
        const float d = fp16_to_f32(rd_u16(blk));
        const float dmin = fp16_to_f32(rd_u16(blk + 2));
        const uint8_t* scales = blk + 4;
        const uint8_t* qh = blk + 16;  // 32 字节高位的 bit 数组，bit 下标 = 块内元素下标
        const uint8_t* qs = blk + 48;
        float* y = out + (size_t)b * 256;
        int is = 0;
        for (int j = 0; j < 256; j += 64) {
          uint8_t sc, mn;
          get_scale_min_k4(is + 0, scales, sc, mn);
          const float d1 = d * (float)sc, m1 = dmin * (float)mn;
          get_scale_min_k4(is + 1, scales, sc, mn);
          const float d2 = d * (float)sc, m2 = dmin * (float)mn;
          const unsigned mask1 = 1u << (2 * (j / 64));
          const unsigned mask2 = 1u << (2 * (j / 64) + 1);
          for (int l = 0; l < 32; ++l) {
            const int h1 = (qh[l] & mask1) ? 16 : 0;
            y[j + l] = d1 * (float)((qs[l] & 0x0F) + h1) - m1;
          }
          for (int l = 0; l < 32; ++l) {
            const int h2 = (qh[l] & mask2) ? 16 : 0;
            y[j + 32 + l] = d2 * (float)((qs[l] >> 4) + h2) - m2;
          }
          qs += 32;
          is += 2;
        }
      }
      return;
    }
    case T_Q6_K: {
      for (int b = 0; b < n / 256; ++b) {
        const uint8_t* blk = row + (size_t)b * 210;
        const float d = fp16_to_f32(rd_u16(blk + 208));
        const uint8_t* ql = blk;
        const uint8_t* qh = blk + 128;
        const int8_t* sc = (const int8_t*)(blk + 192);
        float* y = out + (size_t)b * 256;
        for (int nb = 0; nb < 2; ++nb) {
          for (int l = 0; l < 32; ++l) {
            const int is = l / 16;
            const int q1 = (int)((int8_t)((ql[l + 0] & 0x0F) | (((qh[l] >> 0) & 3) << 4))) - 32;
            const int q2 = (int)((int8_t)((ql[l + 32] & 0x0F) | (((qh[l] >> 2) & 3) << 4))) - 32;
            const int q3 = (int)((int8_t)((ql[l + 0] >> 4) | (((qh[l] >> 4) & 3) << 4))) - 32;
            const int q4 = (int)((int8_t)((ql[l + 32] >> 4) | (((qh[l] >> 6) & 3) << 4))) - 32;
            const float dd = d;
            y[nb * 128 + l + 0] = dd * (float)sc[is + 0] * (float)q1;
            y[nb * 128 + l + 32] = dd * (float)sc[is + 2] * (float)q2;
            y[nb * 128 + l + 64] = dd * (float)sc[is + 4] * (float)q3;
            y[nb * 128 + l + 96] = dd * (float)sc[is + 6] * (float)q4;
          }
          ql += 64;
          qh += 32;
          sc += 8;
        }
      }
      return;
    }
    default:
      for (int i = 0; i < n; ++i) out[i] = 0.f;
      return;
  }
}

// ---------------------------------------------------------------------------
// 简易线程池：parallel_for 按索引分块，主线程也参与。
// ---------------------------------------------------------------------------

class ThreadPool {
 public:
  explicit ThreadPool(int n) {
    if (n > 0) {
      workers_.reserve((size_t)n);
      for (int i = 0; i < n; ++i) workers_.emplace_back([this] { worker(); });
    }
  }
  ~ThreadPool() { stop(); }
  int size() const { return (int)workers_.size(); }

  void parallel_for(int begin, int end, const std::function<void(int)>& fn) {
    if (begin >= end) return;
    if (workers_.empty() || end - begin <= 1) {
      for (int i = begin; i < end; ++i) fn(i);
      return;
    }
    {
      std::lock_guard<std::mutex> lk(mu_);
      task_ = std::make_shared<std::function<void(int)>>(fn);
      begin_ = begin;
      end_ = end;
      const int nw = (int)workers_.size();
      const int chunks = std::min(end - begin, std::max(1, nw * 4));
      chunk_ = std::max(1, (end - begin + chunks - 1) / chunks);
      next_.store(begin, std::memory_order_relaxed);
      epoch_.fetch_add(1, std::memory_order_acq_rel);
      active_.store(nw, std::memory_order_relaxed);
    }
    cv_.notify_all();
    run_epoch();
    std::unique_lock<std::mutex> lk(mu_);
    done_cv_.wait(lk, [this] { return active_.load(std::memory_order_acquire) == 0; });
  }

 private:
  void run_epoch() {
    for (;;) {
      std::shared_ptr<std::function<void(int)>> fn;
      int b, e;
      {
        std::lock_guard<std::mutex> lk(mu_);
        if (next_.load(std::memory_order_relaxed) >= end_) return;
        b = next_.load(std::memory_order_relaxed);
        e = std::min(end_, b + chunk_);
        next_.store(e, std::memory_order_relaxed);
        fn = task_;
      }
      if (fn) {
        for (int i = b; i < e; ++i) (*fn)(i);
      }
    }
  }

  void worker() {
    size_t seen = 0;
    for (;;) {
      {
        std::unique_lock<std::mutex> lk(mu_);
        cv_.wait(lk, [this, seen] {
          return stop_.load(std::memory_order_acquire) || epoch_.load(std::memory_order_acquire) != seen;
        });
        if (stop_.load(std::memory_order_acquire)) return;
        seen = epoch_.load(std::memory_order_acquire);
      }
      run_epoch();
      {
        std::lock_guard<std::mutex> lk(mu_);
        if (active_.fetch_sub(1, std::memory_order_acq_rel) == 1) done_cv_.notify_all();
      }
    }
  }

  void stop() {
    {
      std::lock_guard<std::mutex> lk(mu_);
      stop_.store(true, std::memory_order_release);
    }
    cv_.notify_all();
    for (auto& t : workers_) {
      if (t.joinable()) t.join();
    }
    workers_.clear();
  }

  mutable std::mutex mu_;
  std::condition_variable cv_;
  std::condition_variable done_cv_;
  std::vector<std::thread> workers_;
  std::shared_ptr<std::function<void(int)>> task_;
  int begin_ = 0;
  int end_ = 0;
  int chunk_ = 1;
  std::atomic<int> next_{0};
  std::atomic<size_t> epoch_{0};
  std::atomic<int> active_{0};
  std::atomic<bool> stop_{false};
};

