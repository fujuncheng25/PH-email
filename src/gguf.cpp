static bool cp_is_space(uint32_t cp) {
  int lo = 0, hi = kSpaceCp_n - 1;
  while (lo <= hi) {
    const int mid = (lo + hi) / 2;
    if (cp < kSpaceCp[mid]) {
      hi = mid - 1;
    } else if (cp > kSpaceCp[mid]) {
      lo = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}

// 打开 UTF-8 路径（Windows 下转宽字符，支持中文目录）。
static FILE* fopen_utf8(const std::string& path, const char* mode) {
#ifdef _WIN32
  std::wstring w = std::filesystem::u8path(path).wstring();
  std::wstring wm;
  for (const char* p = mode; *p; ++p) wm.push_back((wchar_t)(unsigned char)*p);
  return _wfopen(w.c_str(), wm.c_str());
#else
  return std::fopen(path.c_str(), mode);
#endif
}

static bool file_size_utf8(const std::string& path, long long& size) {
#ifdef _WIN32
  std::wstring w = std::filesystem::u8path(path).wstring();
  FILE* f = _wfopen(w.c_str(), L"rb");
#else
  FILE* f = std::fopen(path.c_str(), "rb");
#endif
  if (!f) return false;
#ifdef _WIN32
  _fseeki64(f, 0, SEEK_END);
  size = (long long)_ftelli64(f);
#else
  std::fseek(f, 0, SEEK_END);
  size = (long long)std::ftell(f);
#endif
  std::fclose(f);
  return true;
}

