static inline float fp16_to_f32(uint16_t h) {
  const uint32_t sign = (uint32_t)(h & 0x8000u) << 16;
  uint32_t exp = (h >> 10) & 0x1Fu;
  uint32_t mant = h & 0x3FFu;
  uint32_t out;
  if (exp == 0) {
    if (mant == 0) {
      out = sign;
    } else {
      exp = 127 - 15 + 1;
      while ((mant & 0x400u) == 0) {
        mant <<= 1;
        --exp;
      }
      mant &= 0x3FFu;
      out = sign | (exp << 23) | (mant << 13);
    }
  } else if (exp == 31) {
    out = sign | 0x7F800000u | (mant << 13);
  } else {
    out = sign | ((exp - 15 + 127) << 23) | (mant << 13);
  }
  float f;
  std::memcpy(&f, &out, 4);
  return f;
}

static inline float bf16_to_f32(uint16_t h) {
  uint32_t u = (uint32_t)h << 16;
  float f;
  std::memcpy(&f, &u, 4);
  return f;
}

static void utf8_append(std::string& s, uint32_t cp) {
  if (cp < 0x80) {
    s.push_back((char)cp);
  } else if (cp < 0x800) {
    s.push_back((char)(0xC0 | (cp >> 6)));
    s.push_back((char)(0x80 | (cp & 0x3F)));
  } else if (cp < 0x10000) {
    s.push_back((char)(0xE0 | (cp >> 12)));
    s.push_back((char)(0x80 | ((cp >> 6) & 0x3F)));
    s.push_back((char)(0x80 | (cp & 0x3F)));
  } else {
    s.push_back((char)(0xF0 | (cp >> 18)));
    s.push_back((char)(0x80 | ((cp >> 12) & 0x3F)));
    s.push_back((char)(0x80 | ((cp >> 6) & 0x3F)));
    s.push_back((char)(0x80 | (cp & 0x3F)));
  }
}

// 解码一个 UTF-8 码点；非法字节按 1 字节、码点 0xFFFD 处理。
static uint32_t utf8_decode(const std::string& s, size_t i, size_t& len) {
  const unsigned char c = (unsigned char)s[i];
  if (c < 0x80) {
    len = 1;
    return c;
  }
  int extra;
  uint32_t cp;
  if ((c & 0xE0) == 0xC0) {
    extra = 1;
    cp = c & 0x1F;
  } else if ((c & 0xF0) == 0xE0) {
    extra = 2;
    cp = c & 0x0F;
  } else if ((c & 0xF8) == 0xF0) {
    extra = 3;
    cp = c & 0x07;
  } else {
    len = 1;
    return 0xFFFD;
  }
  if (i + 1 + (size_t)extra > s.size()) {
    len = 1;
    return 0xFFFD;
  }
  for (int k = 1; k <= extra; ++k) {
    const unsigned char cc = (unsigned char)s[i + (size_t)k];
    if ((cc & 0xC0) != 0x80) {
      len = 1;
      return 0xFFFD;
    }
    cp = (cp << 6) | (cc & 0x3F);
  }
  len = (size_t)extra + 1;
  return cp;
}

static bool in_ranges(const uint32_t (*r)[2], int n, uint32_t cp) {
  int lo = 0, hi = n - 1;
  while (lo <= hi) {
    const int mid = (lo + hi) / 2;
    if (cp < r[mid][0]) {
      hi = mid - 1;
    } else if (cp > r[mid][1]) {
      lo = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}

