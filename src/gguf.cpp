void Model::unload() {
  impl_->data.clear();
  impl_->data.shrink_to_fit();
  impl_->kv.clear();
  impl_->tensors.clear();
  impl_->index.clear();
  impl_->loaded = false;
}

bool Model::loaded() const { return impl_->loaded; }
const std::string& Model::path() const { return impl_->path; }
size_t Model::file_size() const { return impl_->file_size; }
uint64_t Model::alignment() const { return impl_->alignment; }

bool Model::load(const std::string& path, std::string& err) {
  unload();
  long long fsz = 0;
  if (!file_size_utf8(path, fsz) || fsz <= 0) {
    err = "无法读取模型文件（不存在或不可读）：" + path;
    return false;
  }
  if ((uint64_t)fsz > (uint64_t)64 * 1024 * 1024 * 1024ull) {
    err = "模型文件过大（>64GB）";
    return false;
  }
  FILE* f = fopen_utf8(path, "rb");
  if (!f) {
    err = "无法打开模型文件：" + path;
    return false;
  }
  impl_->data.resize((size_t)fsz);
  const size_t got = std::fread(impl_->data.data(), 1, (size_t)fsz, f);
  std::fclose(f);
  if (got != (size_t)fsz) {
    impl_->data.clear();
    err = "模型文件读取不完整（磁盘错误？）";
    return false;
  }
  impl_->path = path;
  impl_->file_size = (size_t)fsz;

  Reader r{impl_->data.data(), impl_->data.size(), 0, true};
  // magic
  if (!r.need(8)) {
    err = "模型文件太短，不是有效的 GGUF";
    return false;
  }
  if (std::memcmp(r.p, "GGUF", 4) != 0) {
    err = "不是 GGUF 文件（magic 校验失败），可能下载到了错误内容";
    return false;
  }
  r.pos = 4;
  const uint32_t version = r.u32();
  if (version < 2 || version > 3) {
    err = "不支持的 GGUF 版本 " + std::to_string(version) + "（仅支持 v2/v3）";
    return false;
  }
  impl_->version = version;
  const uint64_t n_tensors = r.u64();
  const uint64_t n_kv = r.u64();
  if (!r.ok || n_tensors > 1000000ull || n_kv > 1000000ull) {
    err = "GGUF 头部损坏";
    return false;
  }
  for (uint64_t k = 0; k < n_kv; ++k) {
    std::string key = r.str();
    if (!r.ok) {
      err = "GGUF metadata 读取失败";
      return false;
    }
    const uint32_t type = r.u32();
    KvVal v;
    if (!read_kv_value(r, type, v, err)) {
      if (err.empty()) err = "GGUF metadata 读取失败";
      return false;
    }
    if (key == "general.alignment") {
      const uint64_t a = (v.kind == KvVal::K_UInt) ? v.u : (uint64_t)v.i;
      if (a >= 1 && a <= 4096) impl_->alignment = a;
    }
    impl_->kv[key] = std::move(v);
  }
  impl_->tensors.resize((size_t)n_tensors);
  for (uint64_t k = 0; k < n_tensors; ++k) {
    TensorInfo& t = impl_->tensors[(size_t)k];
    t.name = r.str();
    const uint32_t nd = r.u32();
    if (!r.ok || nd == 0 || nd > 8) {
      err = "GGUF tensor info 损坏";
      return false;
    }
    t.dims.resize(nd);
    for (uint32_t d = 0; d < nd; ++d) t.dims[d] = r.u64();
    t.type = r.u32();
    t.offset = r.u64();
    if (!r.ok) {
      err = "GGUF tensor info 读取失败";
      return false;
    }
    uint64_t ne = 1;
    for (uint64_t d : t.dims) {
      if (d != 0 && ne > std::numeric_limits<uint64_t>::max() / d) {
        err = "GGUF tensor 尺寸溢出";
        return false;
      }
      ne *= d;
    }
    t.nelements = ne;
    int block = 1, bytes = 0;
    if (type_layout(t.type, block, bytes)) {
      if (ne % (uint64_t)block != 0) {
        err = "张量 " + t.name + " 元素数 " + std::to_string(ne) + " 不是块大小 " +
              std::to_string(block) + " 的整数倍（类型 " + type_name(t.type) + "）";
        return false;
      }
      t.nbytes = (size_t)((ne / (uint64_t)block) * (uint64_t)bytes);
    } else {
      t.nbytes = 0;  // 未知类型：加载时忽略，使用时再报错
    }
    impl_->index[t.name] = (size_t)k;
  }
  // data 区按 alignment 对齐
  const uint64_t align = impl_->alignment ? impl_->alignment : 32;
  impl_->data_start = (size_t)(((uint64_t)r.pos + align - 1) / align * align);
  if (impl_->data_start > impl_->data.size()) {
    err = "GGUF 数据区偏移超出文件大小";
    return false;
  }
  const size_t avail = impl_->data.size() - impl_->data_start;
  for (TensorInfo& t : impl_->tensors) {
    if (t.nbytes == 0) {
      t.data = nullptr;
      continue;
    }
    if (t.offset > (uint64_t)avail || t.nbytes > avail - (size_t)t.offset) {
      err = "张量 " + t.name + " 超出文件数据区（文件截断？）";
      return false;
    }
    t.data = impl_->data.data() + impl_->data_start + (size_t)t.offset;
  }
  impl_->loaded = true;
  return true;
}

const Model::TensorInfo* Model::tensor(const std::string& name) const {
  auto it = impl_->index.find(name);
  if (it == impl_->index.end()) return nullptr;
  return &impl_->tensors[it->second];
}

const std::vector<Model::TensorInfo>& Model::tensors() const { return impl_->tensors; }

bool Model::has_kv(const std::string& key) const { return impl_->kv.find(key) != impl_->kv.end(); }

std::string Model::get_str(const std::string& key, const std::string& def) const {
  auto it = impl_->kv.find(key);
  if (it == impl_->kv.end()) return def;
  const KvVal& v = it->second;
  if (v.kind == KvVal::K_Str) return v.s;
  if (v.kind == KvVal::K_UInt) return std::to_string(v.u);
  if (v.kind == KvVal::K_Int) return std::to_string(v.i);
  if (v.kind == KvVal::K_Bool) return v.b ? "true" : "false";
  return def;
}

int64_t Model::get_int(const std::string& key, int64_t def) const {
  auto it = impl_->kv.find(key);
  if (it == impl_->kv.end()) return def;
  const KvVal& v = it->second;
  switch (v.kind) {
    case KvVal::K_UInt: return (int64_t)v.u;
    case KvVal::K_Int: return v.i;
    case KvVal::K_Bool: return v.b ? 1 : 0;
    case KvVal::K_Float: return (int64_t)v.f;
    default: return def;
  }
}

double Model::get_float(const std::string& key, double def) const {
  auto it = impl_->kv.find(key);
  if (it == impl_->kv.end()) return def;
  const KvVal& v = it->second;
  switch (v.kind) {
    case KvVal::K_Float: return v.f;
    case KvVal::K_UInt: return (double)v.u;
    case KvVal::K_Int: return (double)v.i;
    case KvVal::K_Bool: return v.b ? 1.0 : 0.0;
    default: return def;
  }
}

bool Model::get_bool(const std::string& key, bool def) const {
  auto it = impl_->kv.find(key);
  if (it == impl_->kv.end()) return def;
  const KvVal& v = it->second;
  switch (v.kind) {
    case KvVal::K_Bool: return v.b;
    case KvVal::K_UInt: return v.u != 0;
    case KvVal::K_Int: return v.i != 0;
    case KvVal::K_Float: return v.f != 0.0;
    default: return def;
  }
}

const std::vector<std::string>* Model::get_str_array(const std::string& key) const {
  auto it = impl_->kv.find(key);
  if (it == impl_->kv.end()) return nullptr;
  if (it->second.kind != KvVal::K_Array) return nullptr;
  return &it->second.strs;
}

const std::vector<int64_t>* Model::get_int_array(const std::string& key) const {
  auto it = impl_->kv.find(key);
  if (it == impl_->kv.end()) return nullptr;
  if (it->second.kind != KvVal::K_Array) return nullptr;
  return &it->second.ints;
}

